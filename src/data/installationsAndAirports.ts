export function resolveHeliAdminStopCode(
  rawCode: string,
  facilities: InstallationOrAirport[] = INSTALLATIONS_AND_AIRPORTS
): InstallationOrAirport | undefined {
  const clean = (rawCode || '').trim().toUpperCase();
  if (!clean) return undefined;

  const mappedId = HELIADMIN_CODE_TO_FACILITY_ID[clean];
  if (mappedId) {
    const found = facilities.find((f) => f.id === mappedId);
    if (found) return found;
  }

  return facilities.find(
    (f) =>
      f.code.toUpperCase() === clean ||
      (f.heliAdminAliases && f.heliAdminAliases.includes(clean))
  );
}

